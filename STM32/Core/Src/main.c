static void CPU_CACHE_Enable(void)
{
  SCB_EnableICache();
  SCB_EnableDCache();
  SCB->CCR &= ~(uint32_t)SCB_CCR_UNALIGN_TRP_Msk;
  __DSB();
  __ISB();
}

